def find_header_row(file_path, keywords=["confirmation_number", "hotel_code", "arrival_date"]):
    """Finds the header row by counting matches for target keywords."""
    best_row = 0
    max_matches = 0
    with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
        for i, line in enumerate(f):
            if i > 50: break
            matches = sum(1 for word in keywords if word.lower() in line.lower())
            if matches > max_matches:
                max_matches = matches
                best_row = i
            if max_matches >= len(keywords):
                return i
    return best_row

