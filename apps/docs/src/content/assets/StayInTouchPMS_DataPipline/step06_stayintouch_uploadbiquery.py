def run_master_pipeline():
    search_path = os.path.join(NEW_DIR, "*.csv")
    files_to_process = glob.glob(search_path)

    if not files_to_process:
        # Check if we need to pull back from Processed for this run (for testing/demo)
        print("No files in Upload. Checking Processed/Failed for re-processing...")
        for folder in [PROCESSED_DIR, FAILED_DIR]:
            if os.path.exists(folder):
                for f_name in os.listdir(folder):
                    if f_name.endswith('.csv') and "combined_standardized" not in f_name:
                        shutil.move(os.path.join(folder, f_name), os.path.join(NEW_DIR, f_name))
        files_to_process = glob.glob(search_path)

    print(f"Found {len(files_to_process)} files to analyze.")
    all_standardized_dfs = []

    for file_path in files_to_process:
        file_name = os.path.basename(file_path)
        print(f"\nProcessing: {file_name}")

        # Parse Date and Property Code for Filename naming
        # Regex looks for YYYYMMDD and the alphanumeric code following it
        name_match = re.search(r"(\d{8})_([A-Z0-9]+)", file_name, re.IGNORECASE)
        if name_match:
            snap_date_raw = name_match.group(1)
            prop_code = name_match.group(2).upper()
            snap_date_str = pd.to_datetime(snap_date_raw, format="%Y%m%d").strftime("%Y-%m-%d")
            output_filename = f"{snap_date_raw}_{prop_code}_combined_standardized.csv"
        else:
            snap_date_str     = "UNKNOWN"
            prop_code         = "UNKNOWN"
            output_filename   = "combined_standardized_data.csv"

        try:
            header_idx = find_header_row(file_path)
            df = pd.read_csv(file_path, delimiter=',', header=header_idx, on_bad_lines='skip', low_memory=False)

            df_std = standardize_headers(df)
            df_std['property_code'] = prop_code
            df_std['source_file'] = file_name
            df_std['snap_date'] = snap_date_str

            # Save individual standardized file with new naming convention
            export_path = os.path.join(EXPORT_DIR, output_filename)
            df_std.to_csv(export_path, index=False)

            all_standardized_dfs.append(df_std)
            print(f"  ✅ Success: {prop_code} | Exported to: {output_filename}")
            shutil.move(file_path, os.path.join(PROCESSED_DIR, file_name))

        except Exception as e:
            print(f"  ❌ Error: {e}")
            shutil.move(file_path, os.path.join(FAILED_DIR, file_name))

if __name__ == "__main__":
    run_master_pipeline()

