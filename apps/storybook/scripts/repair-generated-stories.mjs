#!/usr/bin/env node

import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const repoRoot = resolve(new URL("../../..", import.meta.url).pathname);
const uiRoot = resolve(repoRoot, "packages/ui/src");
const generatedMarker = "// @generated by Metrics Storybook story generator";

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(path)));
    else if (entry.isFile() && entry.name.endsWith(".stories.tsx"))
      files.push(path);
  }

  return files;
}

function repairTodoBlock(source) {
  const lines = source.split("\n");
  const start = lines.findIndex((line) =>
    line.startsWith(
      "// TODO(story): Provide representative values for required props:",
    ),
  );
  const importIndex = lines.findIndex(
    (line, index) => index > start && line.startsWith("import type "),
  );

  if (start === -1 || importIndex === -1) return source;

  const repaired = [];
  let current = "";

  for (const line of lines.slice(start + 1, importIndex)) {
    if (line.startsWith("// - ")) {
      if (current) repaired.push(current);
      current = line.trim();
    } else if (line.trim()) {
      current += ` ${line.replace(/^\/\/\s?/, "").trim()}`;
    }
  }

  if (current) repaired.push(current);

  return [
    ...lines.slice(0, start + 1),
    ...repaired.map((line) => line.replace(/\s+/g, " ").trim()),
    ...lines.slice(importIndex),
  ].join("\n");
}

function repairObjectKeys(source) {
  return source.replace(
    /^(\s+)([A-Za-z_$][A-Za-z0-9_$]*-[A-Za-z0-9_$-]+):/gm,
    (_match, indent, key) => `${indent}${JSON.stringify(key)}:`,
  );
}

const files = await walk(uiRoot);
let repairedCount = 0;

for (const file of files) {
  const source = await readFile(file, "utf8");
  if (!source.startsWith(generatedMarker)) continue;

  const repaired = repairObjectKeys(repairTodoBlock(source));
  if (repaired !== source) {
    await writeFile(file, repaired, "utf8");
    repairedCount += 1;
  }
}

console.log(`Repaired generated stories: ${repairedCount}`);
